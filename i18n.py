def norm_lang(code):
    """Map anything a browser might send ('pt', 'pt-PT', 'EN-us') to a supported code."""
    if not isinstance(code, str):
        return "en"
    c = code.strip().replace("_", "-")
    for k in LANGS:
        if k.lower() == c.lower():
            return k
    base = c.split("-")[0].lower()
    for k in LANGS:
        if k.split("-")[0].lower() == base:
            return k
    return "en"


